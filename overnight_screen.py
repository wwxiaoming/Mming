def baidu_kline_with_ma(code, start_time=""):
    """百度股市通K线"""
    url = "https://finance.pae.baidu.com/selfselect/getstockquotation"
    params = {
        "all": "1", "isIndex": "false", "isBk": "false", "isBlock": "false",
        "isFutures": "false", "isStock": "true", "newFormat": "1",
        "group": "quotation_kline_ab", "finClientType": "pc",
        "code": code, "start_time": start_time, "ktype": "1",
    }
    headers = {
        "User-Agent": "Mozilla/5.0",
        "Accept": "application/vnd.finance-web.v1+json",
        "Origin": "https://gushitong.baidu.com",
        "Referer": "https://gushitong.baidu.com/",
    }
    try:
        r = requests.get(url, params=params, headers=headers, timeout=10)
        d = r.json()
    except:
        return {"keys": [], "rows": []}

    result = d.get("Result", {})
    # Result可能是dict或list
    if isinstance(result, list) and len(result) > 0:
        result = result[0] if isinstance(result[0], dict) else {}
    if not isinstance(result, dict):
        return {"keys": [], "rows": []}
    md = result.get("newMarketData", {})
    if not isinstance(md, dict):
        return {"keys": [], "rows": []}
    keys = md.get("keys", [])
    rows = md.get("marketData", "").split(";")
    return {"keys": keys, "rows": rows}


def check_ma_and_limitup(code):
    """综合检查均线多头+20天涨停+量能放大"""
    data = baidu_kline_with_ma(code)
    keys = data["keys"]
    rows = data["rows"]

    result = {
        "ma_bullish": False,
        "ma5": 0, "ma10": 0, "ma20": 0,
        "limit_up_20d": False,
        "limit_up_count": 0,
        "vol_increasing": False,
        "vols": [],
    }

    if not keys or len(rows) < 5:
        return result

    # 找字段索引
    idx_map = {}
    for name in ["ma5avgprice", "ma10avgprice", "ma20avgprice", "close", "volume", "change", "pct_chg"]:
        if name in keys:
            idx_map[name] = keys.index(name)

    # 取最近25根K线(多取几根确保20天)
    recent = rows[-25:] if len(rows) >= 25 else rows

    limit_up_count = 0
    vols = []
    ma_values = []

    for row in recent:
        fields = row.split(",")
        if len(fields) < len(keys):
            continue

        try:
            # 涨停检查
            pct_key = "change" if "change" in idx_map else "pct_chg"
            if pct_key in idx_map:
                pct_str = fields[idx_map[pct_key]]
                pct = float(pct_str) if pct_str and pct_str != "-" else 0
                if code.startswith("3") or code.startswith("68"):
                    if pct >= 19.5:
                        limit_up_count += 1
                else:
                    if pct >= 9.5:
                        limit_up_count += 1

            # 成交量
            if "volume" in idx_map:
                vol_str = fields[idx_map["volume"]]
                vol = float(vol_str) if vol_str and vol_str != "-" else 0
                vols.append(vol)

            # 均线
            ma5 = float(fields[idx_map["ma5avgprice"]]) if "ma5avgprice" in idx_map and fields[idx_map["ma5avgprice"]] and fields[idx_map["ma5avgprice"]] != "-" else 0
            ma10 = float(fields[idx_map["ma10avgprice"]]) if "ma10avgprice" in idx_map and fields[idx_map["ma10avgprice"]] and fields[idx_map["ma10avgprice"]] != "-" else 0
            ma20 = float(fields[idx_map["ma20avgprice"]]) if "ma20avgprice" in idx_map and fields[idx_map["ma20avgprice"]] and fields[idx_map["ma20avgprice"]] != "-" else 0
            ma_values.append({"ma5": ma5, "ma10": ma10, "ma20": ma20})
        except (ValueError, IndexError):
            continue

    # 均线多头: 最新一根K线 MA5>MA10>MA20
    if ma_values:
        latest = ma_values[-1]
        result["ma5"] = round(latest["ma5"], 2)
        result["ma10"] = round(latest["ma10"], 2)
        result["ma20"] = round(latest["ma20"], 2)
        if latest["ma5"] > latest["ma10"] > latest["ma20"] > 0:
            result["ma_bullish"] = True

    # 涨停
    result["limit_up_count"] = limit_up_count
    result["limit_up_20d"] = limit_up_count > 0

    # 量能放大
    result["vols"] = vols[-5:]
    if len(vols) >= 3:
        recent_vols = vols[-3:]
        increasing = sum(1 for i in range(1, len(recent_vols)) if recent_vols[i] > recent_vols[i-1])
        result["vol_increasing"] = increasing >= 2

    return result


