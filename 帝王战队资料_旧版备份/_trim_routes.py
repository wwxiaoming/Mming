for fname, sections in all_heroes.items():
    path = os.path.join(base, fname)
    if not os.path.exists(path):
        print(f'SKIP {fname}: not found')
        continue
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Replace B section: from '### 路线B' or '## 路线 B' to just before '### 路线C' or '## 路线 C'
    pattern_b = r'(?:### 路线B|## 路线 B).*?(?=\n(?:### 路线C|## 路线 C))'
    if re.search(pattern_b, content, flags=re.DOTALL):
        content = re.sub(pattern_b, sections['B'], content, flags=re.DOTALL, count=1)
    else:
        # If B section doesn't exist (shouldn't happen), append before C section
        pattern_insert = r'(\n)(### 路线C|## 路线 C)'
        content = re.sub(pattern_insert, r'\1' + sections['B'] + r'\n\n\2', content, count=1)
    
    # Replace C section: from C header to closing ```
    pattern_c = r'(?:### 路线C|## 路线 C).*?(?=\n```\s*$)'
    if re.search(pattern_c, content, flags=re.DOTALL):
        content = re.sub(pattern_c, sections['C'], content, flags=re.DOTALL, count=1)
    
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f'{fname}: OK')

